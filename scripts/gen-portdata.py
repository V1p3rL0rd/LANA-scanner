#!/usr/bin/env python3
"""Regenerate Sources/NetScanner/Model/PortData.swift from an nmap-services file.

Usage:
    curl -fsSLo /tmp/nmap-services https://raw.githubusercontent.com/nmap/nmap/master/nmap-services
    python3 scripts/gen-portdata.py /tmp/nmap-services
"""
import pathlib
import sys


def ranges(ports):
    out, start, prev = [], ports[0], ports[0]
    for p in ports[1:]:
        if p == prev + 1:
            prev = p
            continue
        out.append(f"{start}-{prev}" if start != prev else str(start))
        start = prev = p
    out.append(f"{start}-{prev}" if start != prev else str(start))
    return ",".join(out)


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    rows = []
    for line in pathlib.Path(sys.argv[1]).read_text(encoding="utf-8", errors="replace").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) < 3 or "/" not in parts[1]:
            continue
        port, proto = parts[1].split("/", 1)
        if proto != "tcp":
            continue
        rows.append((float(parts[2]), int(port), parts[0]))
    rows.sort(key=lambda r: -r[0])
    if len(rows) < 1000:
        print("nmap-services looks truncated", file=sys.stderr)
        return 1

    top100 = ranges(sorted(r[1] for r in rows[:100]))
    top1000 = ranges(sorted(r[1] for r in rows[:1000]))
    names = ",".join(f"{p}:{n}" for _, p, n in sorted(rows[:1000], key=lambda r: r[1]) if n != "unknown")

    target = pathlib.Path(__file__).resolve().parent.parent / "Sources/NetScanner/Model/PortData.swift"
    target.write_text(
        "// Generated by scripts/gen-portdata.py from nmap-services (https://nmap.org).\n"
        "// TCP ports ranked by open-frequency. Do not edit by hand.\n\n"
        "enum PortData {\n"
        "    /// Same set as `nmap --top-ports 100` (TCP).\n"
        f'    static let top100 = "{top100}"\n\n'
        "    /// Same set as `nmap --top-ports 1000` (TCP).\n"
        f'    static let top1000 = "{top1000}"\n\n'
        '    /// "port:name" pairs for the top-1000 TCP ports.\n'
        f'    static let serviceNames = "{names}"\n'
        "}\n",
        encoding="utf-8",
    )
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
